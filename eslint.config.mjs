import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

// Flat config replaces (not merges) a rule across overlapping blocks, so each
// block below lists its full set from these shared groups. Relative patterns
// (`**/db`) catch `../db` imports that the `@/` aliases would miss.
const framework = ["react", "react-dom", "next", "next/*"];
const presentation = ["@/app/*", "@/ui/*", "**/ui", "**/ui/*", "**/app", "**/app/*"];
const nodeIo = ["fs", "fs/promises", "net", "http", "http2", "https", "child_process", "dgram", "dns", "tls"];
const ioPackages = ["pg", "ioredis", "bullmq", "undici"];
const io = [...nodeIo, ...nodeIo.map((m) => `node:${m}`), ...ioPackages];
const effectDirs = ["db", "providers", "llm", "queue", "render", "authoring", "net", "wiring"];
const effects = effectDirs.flatMap((d) => [`@/server/${d}`, `@/server/${d}/*`, `**/${d}`, `**/${d}/*`]);
const orm = ["drizzle-orm", "drizzle-orm/*"];
// The vault and its master key are server-only. Client code (src/ui, and .tsx under src/app other than the server-only
// Next entry files) may not import them; server actions (actions.ts) and page/layout/route files may.
const vault = ["@/server/db/vault", "@/server/db/master-key", "**/db/vault", "**/db/master-key"];
const serverEntries = ["page", "layout", "template", "default", "loading", "not-found", "forbidden", "unauthorized"].map((n) => `src/app/**/${n}.tsx`);

const restrict = (...groups) => ({
  "no-restricted-imports": ["error", { patterns: [{ group: groups.flat() }] }],
});

const coreOnly = {
  "no-restricted-globals": [
    "error",
    ...["fetch", "WebSocket", "XMLHttpRequest"].map((name) => ({ name, message: "server/core does no IO; inject a port." }))
  ],
  "no-restricted-syntax": [
    "error",
    { selector: "ImportExpression", message: "server/core does no IO; dynamic import could hide it." }
  ],
};


// Layer boundaries: who may not import whom. Value imports only: `import type` is erased at build, so it cannot create a runtime cycle.
//   providers = adapters (no db, no worker): the wiring layer (src/server/wiring) or an injected port connects them to the database
//   db        = no providers: shared code lives in src/server/net, storage or core
//   ui        = presentation only (no db): data is read in src/app and passed as props
//   app       = no worker code: shared code lives in src/server
// Relative spellings (`../db/x`) are covered too.
const boundary = (files, dirs, message) => ({
  files,
  rules: {
    "@typescript-eslint/no-restricted-imports": [
      "error",
      { patterns: [{ group: dirs.flatMap((d) => [`@/${d}`, `@/${d}/*`, `**/${d.split("/").at(-1)}`, `**/${d.split("/").at(-1)}/*`]), message, allowTypeImports: true }] },
    ],
  },
});
const boundaryRules = [
  boundary(["src/server/providers/**/*.{ts,tsx}"], ["server/db", "worker"], "providers are adapters: inject what they need from the database or the worker (see src/server/wiring; type-only imports are fine)."),
  boundary(["src/server/db/**/*.{ts,tsx}"], ["server/providers"], "db must not depend on providers: move shared code to src/server/net, storage or core (type-only imports are fine)."),
  boundary(["src/ui/**/*.{ts,tsx}"], ["server/db"], "src/ui is presentation: read data in src/app and pass it as props (type-only imports are fine)."),
  boundary(["src/app/**/*.{ts,tsx}"], ["worker"], "the web app must not import worker code: move shared code to src/server."),
];

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated by Playwright.
    "playwright-report/**",
    "test-results/**",
    // Agent tooling, not app code.
    ".claude/**",
    // Plan docs and the frozen old-app snapshot (gitignored, not app code).
    "docs/**",
    // The old app's shorts and skills, copied as read-only references for engine runs (old-kit-import); never built by the app.
    "engine-kit/**",
    // The old app's drawing libraries and their generated declarations: copied as written (old style), bundled only in the render box.
    "remotion/kit/oldlib/**",
    // OpenMontage's composer (AGPL-3.0), copied as written plus patches (engine-kit/openmontage); bundled only in the render box.
    "remotion/kit/om/**",
    "remotion/kit/toon/upstream/**",
    "remotion/kit/om-types/**",
    // Remotion fixture: bundled by Remotion inside the render container, not by Next/tsc.
    "tests/fixtures/remotion-spike/**",
    "tests/fixtures/remotion-tsx/**",
    "tests/fixtures/old-shorts/**"
  ]),
  // Import boundaries (Doc 2 §2). Raw table access is db-only; the package is
  // not installed yet, the rule is pre-wired.
  { files: ["src/**/*.{ts,tsx,mts}"], ignores: ["src/server/**", "src/worker/**"], rules: restrict(orm) },
  {
    files: ["src/ui/**/*.{ts,tsx,mts}", "src/app/**/*.{tsx,jsx}"],
    ignores: serverEntries,
    rules: restrict(orm, vault),
  },
  { files: ["src/server/**/*.{ts,tsx,mts}", "src/worker/**/*.{ts,tsx,mts}"], rules: restrict(framework, presentation, orm) },
  { files: ["src/server/db/**/*.{ts,tsx,mts}"], rules: restrict(framework, presentation) },
  { files: ["src/server/core/**/*.{ts,tsx,mts}"], rules: { ...restrict(framework, presentation, orm, io, effects), ...coreOnly } },
  // Layer boundaries (see boundaryRules above).
  ...boundaryRules,
]);

export default eslintConfig;
