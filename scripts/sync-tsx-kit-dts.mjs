// Copies remotion/kit/tsxlib/yt-kit.d.ts into src/server/core/tsx-kit-dts.ts (server/core may not read files, so the
// declaration text is embedded). Run after editing the .d.ts: node scripts/sync-tsx-kit-dts.mjs
// tests/unit/tsx-kit.test.ts fails when the two differ.
import { readFileSync, writeFileSync } from "node:fs";

const dts = readFileSync(new URL("../remotion/kit/tsxlib/yt-kit.d.ts", import.meta.url), "utf8");
const out = `// GENERATED by scripts/sync-tsx-kit-dts.mjs from remotion/kit/tsxlib/yt-kit.d.ts. Do not edit by hand.\nexport const YT_KIT_DTS: string = ${JSON.stringify(dts)};\n`;
writeFileSync(new URL("../src/server/core/tsx-kit-dts.ts", import.meta.url), out);
