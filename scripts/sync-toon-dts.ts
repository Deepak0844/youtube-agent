// Generates what code scenes need to use the cartoon kit (yt-toon/*): declarations (remotion/kit/toon-types/*.d.ts), the allowed import names
// (src/server/core/toon-names.ts: "yt-toon/<module>" -> its exported value names) and Claude's index (engine-kit/lib/toon.md).
// Run after changing remotion/kit/toon/{core,fx,comic,...}.tsx: npx tsx scripts/sync-toon-dts.ts. tests/unit/tsx-yt-toon.test.ts fails when they drift.
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KIT_DIR = path.join(ROOT, "remotion/kit/toon");
export const TYPES_DIR = path.join(ROOT, "remotion/kit/toon-types");
export const NAMES_FILE = path.join(ROOT, "src/server/core/toon-names.ts");
export const INDEX_FILE = path.join(ROOT, "engine-kit/lib/toon.md");
/** The modules a scene may import, in the order the index lists them. Add a style here when its file exists. */
const ALL_MODULES = ["core", "fx", "comic", "anime", "manga", "paper", "painted"];
export const toonModules = (): string[] => ALL_MODULES.filter((m) => existsSync(path.join(KIT_DIR, `${m}.tsx`)));

const OPTIONS: ts.CompilerOptions = {
  declaration: true, emitDeclarationOnly: true, noEmitOnError: false, outDir: TYPES_DIR, rootDir: KIT_DIR,
  jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022,
  skipLibCheck: true, esModuleInterop: true, allowUmdGlobalAccess: true, strict: true, types: [], allowJs: false,
};

/** Declarations (module and its helpers, flattened to file name -> text) and each module's exported VALUE names. */
export function buildToonDts(): { dts: Map<string, string>; names: Map<string, string[]> } {
  const dts = new Map<string, string>();
  const host = ts.createCompilerHost(OPTIONS, true);
  host.writeFile = (file, text) => {
    const rel = path.relative(TYPES_DIR, file);
    if (file.endsWith(".d.ts") && !rel.startsWith("upstream") && !rel.startsWith("..")) dts.set(rel, text);
  };
  const roots = toonModules().map((m) => path.join(KIT_DIR, `${m}.tsx`));
  const program = ts.createProgram({ rootNames: roots, options: OPTIONS, host });
  program.emit();
  const checker = program.getTypeChecker();
  const names = new Map<string, string[]>();
  for (const m of toonModules()) {
    const sf = program.getSourceFile(path.join(KIT_DIR, `${m}.tsx`))!;
    const sym = checker.getSymbolAtLocation(sf)!;
    names.set(m, checker.getExportsOfModule(sym).filter((s) => ((s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s).flags & ts.SymbolFlags.Value) !== 0).map((s) => s.name).sort());
  }
  return { dts: new Map([...dts].sort(([a], [b]) => a.localeCompare(b))), names };
}

export function namesModule(names: Map<string, string[]>): string {
  const entries = [...names].map(([m, n]) => `  "yt-toon/${m}": ${JSON.stringify(n)},`);
  return `// GENERATED by scripts/sync-toon-dts.ts from remotion/kit/toon. Do not edit by hand.\n// The cartoon kit (yt-toon, drawn by cartoon-shorts' own code, MIT) code scenes may import, and exactly the value names each module exports.\nexport const TOON_LIBS: Readonly<Record<string, readonly string[]>> = {\n${entries.join("\n")}\n};\n`;
}

/** Claude's index: each module's import line and its full declaration (props included), so it cannot drift. */
export function indexDoc(dts: Map<string, string>, names: Map<string, string[]>): string {
  const parts = [...names].map(([m, n]) => `## yt-toon/${m}\n\n\`import { ${n.join(", ")} } from "yt-toon/${m}";\`\n\n\`\`\`ts\n${(dts.get(`${m}.d.ts`) ?? "").trim()}\n\`\`\`\n`);
  return `# Cartoon scenes: the yt-toon kit\n\nGENERATED by scripts/sync-toon-dts.ts. Cartoon-shorts' own puppets, set pieces and looks (MIT), as React components. A cartoon scene file\nimports them with named imports, one module per file below. Times are beat marks (B5, B5e, B5%60, B5+.3), scene ids (hook, hooke, hook+1) or seconds.\n\n${parts.join("\n")}`;
}

/** Writes the declarations, names and index. */
export function syncToonDts(): void {
  const { dts, names } = buildToonDts();
  rmSync(TYPES_DIR, { recursive: true, force: true });
  mkdirSync(TYPES_DIR, { recursive: true });
  for (const [rel, text] of dts) writeFileSync(path.join(TYPES_DIR, rel), text);
  writeFileSync(NAMES_FILE, namesModule(names));
  mkdirSync(path.dirname(INDEX_FILE), { recursive: true });
  writeFileSync(INDEX_FILE, indexDoc(dts, names));
  console.log(`wrote ${dts.size} declaration files`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) syncToonDts();
