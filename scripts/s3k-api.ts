// `npm run s3k:api`: writes remotion/kit/s3k/API.md, the compact reference a model reads before writing a scene file.
// It is generated from the typed manifest remotion/kit/s3k/api.d.ts (every export documented with one comment line), the preset numbers in
// presets.ts and the header comments of the example files. `npm run s3k:api -- --check` fails when API.md is stale (a unit test does the same).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PRESET_LIMITS, WORLD_PRESETS } from "../remotion/kit/s3k/presets";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KIT = path.join(root, "remotion", "kit", "s3k");

const RULES = `# s3k kit API (generated by \`npm run s3k:api\` from api.d.ts: do not edit by hand)
Write one scene file that imports ONLY from "s3k" and "three" (plus react and remotion basics). Units: metres, seconds, degrees; y is up; the cut face is the plane z = 0 and the viewer is on +z.

## Rules (each one prevents a look that was rejected)
1. Order inside <Stage>: <World/> first, then your objects, <CameraRig/>, and <Finish/> LAST.
2. Nothing floats: place every object with rest(object, plane) (or models.get(...) which already stands on y = 0). Never guess a y.
3. All motion is a pure function of t from useT(): build once in useMemo, then call part.update(t) each render. No Math.random (use rnd(seed)), no state between frames, no Date, no timers.
4. Build in useMemo keyed by [models]; never create meshes, textures or materials per frame. Repeating things use instance(); keep draw calls low.
5. Frame the focus, not the world: portrait is narrow. A shot should fill 0.5..1 of the safe area (coverage.fill); use { frame: { box } } shots and check onReport.
6. Camera never below ground or water: pass floor to CameraRig. Keep the sun's focus box tight (World focus) so shadows stay crisp.
7. Strata and ground textures are world-aligned (a pebble has one size everywhere); tile = metres per texture tile.
8. Captions: <=32 characters, one per shot, through Stage overlay={<Captions items={...}/>}.
9. Models come from catalogue ids through useModels(ids, resolver); render nothing until it returns non-null.
10. Copy from the examples (below): they are plain readable code, not magic.

## Skeleton
\`\`\`tsx
const models = useModels(IDS, resolver);            // inside the canvas, in a component
const parts = useMemo(() => models && build(models), [models]);   // build once
parts.update(useT());                                // every render
<Stage overlay={<Captions items={CAPS} />}>
  <World focus={BOX} ground={{ y: 0, zMax: 0 }} sea={{ y: -29, zMin: 0 }} />
  <CutawayBox x0={-420} x1={420} bottom={-70} holes={[HOLE]} />
  <primitive object={parts.root} />
  <CameraRig shots={SHOTS} floor={1.5} />
  <Finish />
</Stage>
\`\`\`
`;

/** The generated sections of the reference (title + text), in order. */
export type Section = { title: string; text: string };

export function parseManifest(dts: string): Section[] {
  const lines = dts.split("\n").filter((l) => !l.startsWith("import ") && !(l.startsWith("//") && !l.startsWith("// ##")));
  const out: Section[] = [];
  let cur: Section = { title: "Types", text: "" };
  for (const l of lines) {
    const m = /^\/\/ ## (.+)$/.exec(l);
    if (m) { if (cur.text.trim()) out.push(cur); cur = { title: m[1]!, text: "" }; continue; }
    if (l.trim() === "") continue;
    cur.text += `${l}\n`;
  }
  if (cur.text.trim()) out.push(cur);
  return out;
}

const fmt = (n: number) => String(n);
function presetTable(): string {
  const rows = (Object.keys(WORLD_PRESETS) as (keyof typeof WORLD_PRESETS)[]).map((k) => {
    const p = WORLD_PRESETS[k];
    return `- ${k}: fogDensity ${fmt(p.fogDensity)}, sun ${fmt(p.sunIntensity)} at ${fmt(p.sunElevationDeg)} deg elevation, exposure ${fmt(p.exposure)}, fog ${p.fog}`;
  });
  const lim = Object.entries(PRESET_LIMITS).map(([k, [a, b]]) => `${k} ${a}..${b}`).join(", ");
  return `${rows.join("\n")}\nLimits: ${lim}.`;
}

function examplesSection(): string {
  const dir = path.join(KIT, "examples");
  const files = readdirSync(dir).filter((f) => /\.(ts|tsx)$/.test(f) && f !== "index.ts").sort();
  const lines = files.map((f) => {
    const src = readFileSync(path.join(dir, f), "utf8").split("\n");
    const head = src.find((l) => l.startsWith("//"))?.replace(/^\/\/\s*/, "") ?? "";
    const exp = src.filter((l) => /^export (function build|const \w+Scene\b)/.test(l)).map((l) => l.replace(/ \{$/, "").replace(/ => \{$/, "").replace(/ = \(.*$/, "").slice(0, 170));
    return `- examples/${f}: ${head.slice(0, 200)}${exp.length ? `\n    ${exp.join("\n    ")}` : ""}`;
  });
  return `Every hero builder returns { root, update(t) }: add root to the scene once, call update(t) every render. Read the file's header comment: it says WHAT TO COPY.\n${lines.join("\n")}`;
}

export function buildApiMd(): string {
  const sections = parseManifest(readFileSync(path.join(KIT, "api.d.ts"), "utf8"));
  const body = sections.map((s) => `## ${s.title}\n\`\`\`ts\n${s.text}\`\`\`\n`).join("\n");
  return `${RULES}\n## Presets\n${presetTable()}\n\n${body}\n## Examples (imitate these)\n${examplesSection()}\n`;
}

/** Size in bytes of each generated section (the unit test keeps them compact). */
export const sectionSizes = (): Record<string, number> => Object.fromEntries(parseManifest(readFileSync(path.join(KIT, "api.d.ts"), "utf8")).map((s) => [s.title, Buffer.byteLength(s.text)]));

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const file = path.join(KIT, "API.md");
  const md = buildApiMd();
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== md) { console.error("API.md is stale: run npm run s3k:api"); process.exit(1); }
    console.log("API.md is up to date");
  } else {
    writeFileSync(file, md);
    console.log(`wrote ${file} (${Buffer.byteLength(md)} bytes)`);
  }
}
