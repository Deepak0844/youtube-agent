// Generates the declarations of the old drawing libraries (remotion/kit/oldlib -> oldlib/types/*.d.ts) and the allowed
// import names Claude's code may use (src/server/core/oldlib-names.ts: "yt-old/<lib>" -> exported VALUE names), like yt-kit.
// Run after changing a library: npx tsx scripts/sync-oldlib-dts.ts. tests/unit/oldlib-names.test.ts fails when they drift.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { kitDocs, kitExportNames } from "../src/server/core/tsx-kit";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OLDLIB_DIR = path.join(ROOT, "remotion/kit/oldlib");
export const TYPES_DIR = path.join(OLDLIB_DIR, "types");
export const NAMES_FILE = path.join(ROOT, "src/server/core/oldlib-names.ts");
/** The index Claude reads in its workspace (seeded to work/ref/lib/index.md). */
export const INDEX_FILE = path.join(ROOT, "engine-kit/lib/index.md");

/** The libraries Claude may import: top-level files of oldlib (geo/ stays internal to map.tsx). */
export const libFiles = (): string[] => readdirSync(OLDLIB_DIR).filter((f) => /\.tsx?$/.test(f) && !f.endsWith(".d.ts")).sort();

/** Emits the declarations in memory: relative path under types/ -> text. */
export function buildOldlibDts(): Map<string, string> {
  const roots = libFiles().map((f) => path.join(OLDLIB_DIR, f));
  const options: ts.CompilerOptions = {
    declaration: true, emitDeclarationOnly: true, noEmitOnError: false, outDir: TYPES_DIR, rootDir: OLDLIB_DIR,
    jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022,
    skipLibCheck: true, esModuleInterop: true, strict: false, types: [],
  };
  const out = new Map<string, string>();
  const host = ts.createCompilerHost(options, true);
  host.writeFile = (file, text) => out.set(path.relative(TYPES_DIR, file).split(path.sep).join("/"), text);
  ts.createProgram({ rootNames: roots, options, host }).emit();
  return out;
}

/** Exported constants declared as a plain string, number or boolean (literal or keyword type): safe to use as plain values. */
export function plainValueNames(dts: string): string[] {
  const sf = ts.createSourceFile("x.d.ts", dts, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
  const plain = new Set([ts.SyntaxKind.StringKeyword, ts.SyntaxKind.NumberKeyword, ts.SyntaxKind.BooleanKeyword]);
  const out: string[] = [];
  for (const st of sf.statements) {
    if (!ts.isVariableStatement(st) || !(ts.getModifiers(st) ?? []).some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
    for (const d of st.declarationList.declarations) {
      if (!ts.isIdentifier(d.name)) continue;
      const lit = d.initializer && (ts.isStringLiteral(d.initializer) || ts.isNumericLiteral(d.initializer) || d.initializer.kind === ts.SyntaxKind.TrueKeyword || d.initializer.kind === ts.SyntaxKind.FalseKeyword || (ts.isPrefixUnaryExpression(d.initializer) && ts.isNumericLiteral(d.initializer.operand)));
      const typed = d.type && (plain.has(d.type.kind) || ts.isLiteralTypeNode(d.type));
      if (lit || typed) out.push(d.name.text);
    }
  }
  return out;
}

export function namesModule(dts: Map<string, string>): string {
  const entries = libFiles().map((f) => {
    const name = f.replace(/\.tsx?$/, "");
    return `  "yt-old/${name}": ${JSON.stringify(kitExportNames(dts.get(`${name}.d.ts`) ?? ""))},`;
  });
  const plain = libFiles().flatMap((f) => {
    const name = f.replace(/\.tsx?$/, "");
    const p = plainValueNames(dts.get(`${name}.d.ts`) ?? "");
    return p.length ? [`  "yt-old/${name}": ${JSON.stringify(p)},`] : [];
  });
  return `// GENERATED by scripts/sync-oldlib-dts.ts from remotion/kit/oldlib. Do not edit by hand.\n// The old app's drawing libraries Claude's code may import, and exactly the value names each one exports.\nexport const OLD_LIBS: Readonly<Record<string, readonly string[]>> = {\n${entries.join("\n")}\n};\n\n// Of those, the constants declared as a plain string, number or boolean: a scene may use them as plain values (fontFamily: FONT_MONO).\n// Every other import stays usable only as X(...) or X.name, as for yt-kit.\nexport const OLD_LIB_PLAIN: Readonly<Record<string, readonly string[]>> = {\n${plain.join("\n")}\n};\n`;
}

/** One section per library: its import name and every export with its parameters (from the declarations, so it cannot drift). */
export function indexDoc(dts: Map<string, string>): string {
  const parts = libFiles().map((f) => {
    const name = f.replace(/\.tsx?$/, "");
    return `## yt-old/${name}\n\n${kitDocs(dts.get(`${name}.d.ts`) ?? "") || "(no exports)"}\n`;
  });
  return `# The old app's drawing libraries\n\nGENERATED by scripts/sync-oldlib-dts.ts. Import with named imports only, e.g. \`import { BigTitle, ProgressBar } from "yt-old/shorts";\`.\nOnly the names listed here exist. The old shorts in ref/examples show them in use (their old \`../../lib/<name>\` imports are now \`yt-old/<name>\`).\n\n${parts.join("\n")}`;
}

function main(): void {
  const dts = buildOldlibDts();
  rmSync(TYPES_DIR, { recursive: true, force: true });
  for (const [rel, text] of dts) {
    const file = path.join(TYPES_DIR, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  writeFileSync(NAMES_FILE, namesModule(dts));
  mkdirSync(path.dirname(INDEX_FILE), { recursive: true });
  writeFileSync(INDEX_FILE, indexDoc(dts));
  console.log(`wrote ${dts.size} declaration files and ${libFiles().length} library entries`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
