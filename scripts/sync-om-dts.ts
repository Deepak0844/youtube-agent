// Generates what code scenes need to use OpenMontage's composer components (OpenMontage parity, Phase C, bespoke path):
// declarations (remotion/kit/om-types/*.d.ts), the allowed import names (src/server/core/om-names.ts: "yt-om/<Component>" ->
// its exported value names) and Claude's index (engine-kit/openmontage/ref/COMPONENTS.md). One module per component file of
// remotion/kit/om/components (the charts included); index files are not modules. Run after an OpenMontage sync:
// npx tsx scripts/sync-om-dts.ts. tests/unit/tsx-yt-om.test.ts fails when they drift.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { kitExportNames } from "../src/server/core/tsx-kit";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const COMPONENTS_DIR = path.join(ROOT, "remotion/kit/om/components");
export const TYPES_DIR = path.join(ROOT, "remotion/kit/om-types");
export const NAMES_FILE = path.join(ROOT, "src/server/core/om-names.ts");
export const INDEX_FILE = path.join(ROOT, "engine-kit/openmontage/ref/COMPONENTS.md");

/** The component files a scene may import: every .tsx under components/ and components/charts/. */
export const componentFiles = (): string[] =>
  ["", "charts"].flatMap((sub) => readdirSync(path.join(COMPONENTS_DIR, sub)).filter((f) => f.endsWith(".tsx")).map((f) => path.join(COMPONENTS_DIR, sub, f))).sort();
const moduleName = (file: string) => path.basename(file).replace(/\.tsx$/, "");

/** Emits the declarations in memory, flattened: <Component>.d.ts -> text. */
export function buildOmDts(): Map<string, string> {
  const options: ts.CompilerOptions = {
    declaration: true, emitDeclarationOnly: true, noEmitOnError: false, outDir: TYPES_DIR, rootDir: COMPONENTS_DIR,
    jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022,
    skipLibCheck: true, esModuleInterop: true, allowUmdGlobalAccess: true, strict: false, types: [],
  };
  const out = new Map<string, string>();
  const host = ts.createCompilerHost(options, true);
  host.writeFile = (file, text) => {
    // charts/BarChart.d.ts -> BarChart.d.ts; their relative imports of each other stay valid (no chart imports another)
    if (file.endsWith(".d.ts")) out.set(path.basename(file), text);
  };
  ts.createProgram({ rootNames: componentFiles(), options, host }).emit();
  return new Map([...out].filter(([f]) => componentFiles().some((c) => `${moduleName(c)}.d.ts` === f)).sort(([a], [b]) => a.localeCompare(b)));
}

export function namesModule(dts: Map<string, string>): string {
  const entries = componentFiles().map((f) => `  "yt-om/${moduleName(f)}": ${JSON.stringify(kitExportNames(dts.get(`${moduleName(f)}.d.ts`) ?? ""))},`);
  return `// GENERATED by scripts/sync-om-dts.ts from remotion/kit/om/components. Do not edit by hand.\n// OpenMontage's composer components (AGPL-3.0) Claude's code scenes may import, and exactly the value names each one exports.\nexport const OM_LIBS: Readonly<Record<string, readonly string[]>> = {\n${entries.join("\n")}\n};\n`;
}

/** Claude's index: each module's import line and its full declaration (props interfaces included), so it cannot drift. */
export function indexDoc(dts: Map<string, string>): string {
  const parts = componentFiles().map((f) => {
    const m = moduleName(f);
    const names = kitExportNames(dts.get(`${m}.d.ts`) ?? "");
    return `## yt-om/${m}\n\n\`import { ${names.join(", ")} } from "yt-om/${m}";\`\n\n\`\`\`ts\n${(dts.get(`${m}.d.ts`) ?? "").trim()}\n\`\`\`\n`;
  });
  return `# OpenMontage's composer components for code scenes\n\nGENERATED by scripts/sync-om-dts.ts (ours; the components are OpenMontage's, AGPL-3.0). For the bespoke path only: a code scene\n(\`scene/video.tsx\`) may import these with named imports, one module per component. They are the same components the\nExplainer composition draws; in the templated path use \`om/composition.json\` instead.\n\n${parts.join("\n")}`;
}

/** Writes the declarations, names and index (also run by npm run openmontage:sync after an update). */
export function syncOmDts(): void {
  const dts = buildOmDts();
  rmSync(TYPES_DIR, { recursive: true, force: true });
  mkdirSync(TYPES_DIR, { recursive: true });
  for (const [rel, text] of dts) writeFileSync(path.join(TYPES_DIR, rel), text);
  writeFileSync(NAMES_FILE, namesModule(dts));
  writeFileSync(INDEX_FILE, indexDoc(dts));
  console.log(`wrote ${dts.size} declaration files`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) syncOmDts();
